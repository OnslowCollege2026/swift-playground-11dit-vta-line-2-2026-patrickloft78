@main
struct SwiftPlayground {
    static func main() {
        let x = 10
        let y = 5
        let added = x + y 
        let subtracted = x - y
        let multiplied = x*y
        let divided = x / y
        print("\(x) + \(y) = \(added)")
        print("\(x) - \(y) = \(subtracted)")  
        print("\(x) * \(y) = \(multiplied)")
        print("\(x) / \(y) = \(divided)")  
       
    }
}
